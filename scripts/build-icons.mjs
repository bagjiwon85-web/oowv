// Collects every icon name used in src/*.tsx and writes a small subset file,
// so the bundle doesn't ship all 3000+ Fluent Emoji icons. Fails on unknown names.
import fs from 'node:fs';
import path from 'node:path';
import {createRequire} from 'node:module';

const require = createRequire(import.meta.url);
const set = require('@iconify-json/fluent-emoji-flat/icons.json');
const srcDir = path.resolve('src');
const names = new Set();
const required = new Set();
for (const f of fs.readdirSync(srcDir)) {
  if (!f.endsWith('.tsx')) continue;
  const code = fs.readFileSync(path.join(srcDir, f), 'utf8');
  // Explicit attributes must resolve; any other matching literal (e.g. constants) is picked up too.
  for (const m of code.matchAll(/\b(?:icon|name)="([a-z0-9-]+)"/g)) required.add(m[1]);
  for (const m of code.matchAll(/['"]([a-z0-9]+(?:-[a-z0-9]+)*)['"]/g)) names.add(m[1]);
}
for (const n of required) names.add(n);
const out = {};
const missing = [];
for (const n of [...names].sort()) {
  const target = set.icons[n] ? n : set.aliases?.[n]?.parent;
  if (!target) {
    if (required.has(n)) missing.push(n);
  }
  else out[n] = set.icons[target].body;
}
if (missing.length) {
  console.error('Unknown icons:', missing.join(', '));
  process.exit(1);
}
fs.writeFileSync(
  path.join(srcDir, 'icons.generated.ts'),
  `// Generated by scripts/build-icons.mjs — do not edit.\nexport const ICONS: Record<string, string> = ${JSON.stringify(out, null, 1)};\n`,
);
console.log(`icons: ${Object.keys(out).length}`);
